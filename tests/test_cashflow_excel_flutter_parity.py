from io import BytesIO
from zipfile import ZipFile

from q_flow.reports.cashflow_excel import build_cashflow_excel
from tests.test_cashflow_excel import _snapshot


_PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def _xlsx_text(data: bytes, path: str) -> str:
    with ZipFile(BytesIO(data)) as archive:
        return archive.read(path).decode("utf-8")


def test_backend_excel_matches_flutter_final_branding_and_layout_polish():
    data = build_cashflow_excel(
        project_name="Harbour Tower",
        snapshot=_snapshot(),
        logo_bytes=_PNG_SIGNATURE,
    )

    sheet = _xlsx_text(data, "xl/worksheets/sheet1.xml")
    strings = _xlsx_text(data, "xl/sharedStrings.xml")
    drawing = _xlsx_text(data, "xl/drawings/drawing1.xml")
    drawing_rels = _xlsx_text(data, "xl/drawings/_rels/drawing1.xml.rels")
    content_types = _xlsx_text(data, "[Content_Types].xml")

    # Flutter's final pass leaves B1 unmerged, indents the brand to clear the
    # 17 mm logo, and puts the generated-by hyperlink in N1.
    assert 'ref="B1:M1"' not in sheet
    assert 'ref="B1:N1"' not in sheet
    assert "\u00a0\u00a0\u00a0CashFlowPot" in strings
    assert "HYPERLINK(&quot;https://cashflowpot.com&quot;,&quot;generated by cashflowpot.com&quot;)" in sheet

    # The Flutter final layout widens I and merges C:D for the left-side
    # assumptions/KPIs.
    assert 'min="9" max="9"' in sheet
    for ref in ("C6:D6", "C7:D7", "C8:D8", "C9:D9", "C11:D11", "C12:D12", "C13:D13", "C14:D14"):
        assert f'ref="{ref}"' in sheet

    # Match the final chart/logo drawing geometry used by the approved report.
    assert 'y="4179400"' in drawing
    assert 'cx="4680000" cy="2880000"' in drawing
    assert '<xdr:pic>' in drawing
    assert 'cx="612000" cy="612000"' in drawing
    assert 'relationships/image' in drawing_rels
    assert 'Extension="png"' in content_types
    with ZipFile(BytesIO(data)) as archive:
        assert archive.read("xl/media/cashflowpot_logo.png") == _PNG_SIGNATURE
